#!/usr/bin/env python3
"""Copy the Android version name into each standalone desktop package."""
from pathlib import Path
import re
import sys

root = Path(__file__).resolve().parent.parent
gradle = (root / "app/build.gradle.kts").read_text(encoding="utf-8")
match = re.search(r'^\s*versionName\s*=\s*"([^"\n]+)"', gradle, re.MULTILINE)
if not match or not re.fullmatch(r"[0-9]+(?:\.[0-9]+)+", match.group(1)):
    sys.exit("Cannot find a valid Android versionName")
content = f'# Generated by scripts/sync-desktop-versions.py.\nVERSION = "{match.group(1)}"\n'
check = sys.argv[1:] == ["--check"]
if sys.argv[1:] not in ([], ["--check"]):
    sys.exit("Usage: sync-desktop-versions.py [--check]")
for platform in ("omarchy", "ubuntu", "windows"):
    path = root / platform / "version.py"
    if check:
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            sys.exit(f"Version out of sync: {path}")
    else:
        path.write_text(content, encoding="utf-8")
print(f"Desktop versions {'match' if check else 'set to'} {match.group(1)}")
